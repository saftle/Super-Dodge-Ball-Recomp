#!/usr/bin/env python3
"""watch_tas.py — play a canonical tas.json in the visible window.

The cycle host forces headless mode for --input/--frames, so scripted TAS
playback in a window uses the windowed path instead: --virtual-pad (an SDL
virtual controller on an absolute-state schedule, same semantics as the
headless --input schedule) plus --exit-after to close at the end.

Mapping (window default bindings, cyc_input.c): NES A->a, B->x,
SELECT->back, START->start, UP/DOWN/LEFT/RIGHT->dpup/dpdown/dpleft/dpright.
Player 1 defaults to keyboard, so a minimal --config flips Player1Source to
the controller the virtual pad attaches. --ram-init zeros matches the
verified TAS-diff power-on state.

Usage:
  python3 tools/tas/watch_tas.py [--tas tas/sdb_4976.tas.json] [--frames N]
      [--out tas/runs/watch] [--no-exit] [--scale 3] [--rom ROM]
"""
import argparse
import json
import os
import subprocess
import sys

PROJ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ROM_DEFAULT = os.path.join(PROJ, "roms", "Super Dodge Ball (USA).nes")
CYC_DIR = os.path.join(PROJ, "build-cycle")
CYC_EXE = os.path.join(CYC_DIR, "nes_game")

# TAS mask bit -> SDL controller name (window default pad bindings).
NAMES = [(0x80, "a"), (0x40, "x"), (0x20, "back"), (0x10, "start"),
         (0x08, "dpup"), (0x04, "dpdown"), (0x02, "dpleft"), (0x01, "dpright")]


def find_opposing(frames):
    """Frames with UP+DOWN or LEFT+RIGHT together.

    The windowed frontend (cyc_input_eval) cancels opposing directions —
    a real pad cannot press both — so these frames can never play back
    exactly in a window. The headless --input path and Mesen pass both bits
    through, as hardware would. Returns [(frame, mask)].
    """
    return [(f, m) for f, m in enumerate(frames)
            if (m & 0x0C) == 0x0C or (m & 0x03) == 0x03]


def emit_vpad(frames, path):
    steps = []
    prev = None
    for f, m in enumerate(frames):
        if m != prev:
            steps.append(f"{f} " + ("+".join(n for bit, n in NAMES if m & bit) if m else "-"))
            prev = m
    with open(path, "w") as f:
        f.write("# generated by watch_tas.py from tas.json (SDL virtual-pad schedule)\n")
        f.write("\n".join(steps) + "\n")
    return steps


def ensure_windowed_build():
    cache = os.path.join(CYC_DIR, "CMakeCache.txt")
    headless_on = None
    if os.path.exists(cache):
        for line in open(cache):
            if line.startswith("NESRECOMP_HEADLESS:"):
                headless_on = line.strip().endswith("=ON")
    if headless_on is False and os.path.exists(CYC_EXE):
        return False
    rom = ROM_DEFAULT
    cfg = os.path.join(PROJ, "src", "game.toml")
    sdl_dir = "/usr/lib/x86_64-linux-gnu/cmake/SDL2"
    cfg_cmd = ["cmake", "-S", "external/nesrecomp/runner/cyc/project", "-B", "build-cycle",
               f"-DNESRECOMP_ROM={rom}", f"-DNESRECOMP_GAME_CONFIG={cfg}",
               "-DNESRECOMP_HEADLESS=OFF"]
    if os.path.isdir(sdl_dir):
        cfg_cmd.append(f"-DSDL2_DIR={sdl_dir}")
    for step in (cfg_cmd, ["cmake", "--build", "build-cycle", "-j", str(os.cpu_count() or 4)]):
        print("[watch] +", " ".join(step[:4]), "...", file=sys.stderr)
        r = subprocess.run(step, cwd=PROJ)
        if r.returncode != 0:
            raise RuntimeError("windowed cycle build step failed")
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tas", default=os.path.join(PROJ, "tas", "sdb_4976.tas.json"))
    ap.add_argument("--frames", type=int, default=None,
                    help="play only the first N TAS frames (default: whole file)")
    ap.add_argument("--out", default=os.path.join(PROJ, "tas", "runs", "watch"))
    ap.add_argument("--rom", default=ROM_DEFAULT)
    ap.add_argument("--no-exit", action="store_true",
                    help="leave the window open at the last input (default: close at end)")
    ap.add_argument("--scale", type=int, default=None)
    ap.add_argument("--dry-run", action="store_true",
                    help="write schedules, print the launch command, do not open a window")
    a = ap.parse_args()

    for p in (a.tas, a.rom):
        if not os.path.exists(p):
            sys.exit(f"missing: {p}")
    tas = json.load(open(a.tas))
    frames = tas["frames"][:a.frames] if a.frames else tas["frames"]
    opp = find_opposing(frames)
    if opp:
        print(f"[watch] NOTE: {len(opp)} frames press opposing d-pad "
              f"directions (first frame {opp[0][0]}); the windowed frontend "
              f"cancels those to neutral while headless/Mesen play both bits. "
              f"Windowed output is verified pixel-identical to headless "
              f"through frame 501, so this affects only those late frames",
              file=sys.stderr)
    os.makedirs(a.out, exist_ok=True)
    vpad = os.path.join(a.out, "watch.vpad")
    steps = emit_vpad(frames, vpad)
    cfg_path = os.path.join(a.out, "watch.ini")
    open(cfg_path, "w").write("[Input]\nPlayer1Source = 2\n")
    print(f"[watch] tas frames={len(frames)} vpad steps={len(steps)}", file=sys.stderr)

    ensure_windowed_build()

    cmd = [CYC_EXE, os.path.abspath(a.rom),
           "--ram-init", "zeros",
           "--virtual-pad", os.path.abspath(vpad),
           "--config", os.path.abspath(cfg_path)]
    if a.scale:
        cmd += ["--scale", str(a.scale)]
    if not a.no_exit:
        cmd += ["--exit-after", str(len(frames))]
    print("[watch] +", " ".join(cmd), file=sys.stderr)
    if a.dry_run:
        return
    sys.stdout.flush()
    r = subprocess.run(cmd, cwd=PROJ)
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
